def domain_for(name: str, slugs: list) -> str:
    if name in DOMAIN_OVERRIDES:
        return DOMAIN_OVERRIDES[name]
    base = slugs[0] if slugs else slugify(name)
    base = base.replace("_", "-").strip("-")
    return f"{base}.com" if base else ""


def main() -> None:
    firms = []
    seen = set()
    for category, rows in CATEGORIES:
        for name, regions, hints, extra in rows:
            key = name.lower()
            if key in PRUNE:
                continue
            if key in seen:
                print(f"duplicate firm skipped: {name}", file=sys.stderr)
                continue
            seen.add(key)
            slugs = slug_candidates(name, extra)
            firms.append({
                "name": name,
                "category": category,
                "regions": [r.strip() for r in regions.split(",") if r.strip()],
                "domain": domain_for(name, slugs),
                "ats": list(hints),
                "slugs": slugs,
            })

    doc = {
        "version": 1,
        "note": (
            "ats entries are HINTS probed first. The resolver validates every "
            "candidate and writes confirmed sources to data/resolved.json. "
            "Add a firm by appending a block here; leave `ats` empty to let "
            "the resolver discover it."
        ),
        "firms": firms,
    }
    yaml.safe_dump(doc, sys.stdout, sort_keys=False, allow_unicode=True, width=100)
    print(f"\n# {len(firms)} firms", file=sys.stderr)


if __name__ == "__main__":
    main()
