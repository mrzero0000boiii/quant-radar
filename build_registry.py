def slugify(name: str, drop_stopwords: bool = False) -> str:
    s = name.lower()
    s = s.replace("&", "and").replace(".", "").replace("'", "")
    words = re.split(r"[^a-z0-9]+", s)
    words = [w for w in words if w]
    if drop_stopwords:
        kept = [w for w in words if w not in STOPWORDS]
        if kept:
            words = kept
    return "".join(words)


def slug_candidates(name: str, extra: list) -> list:
    cands = []
    for c in extra:
        if c not in cands:
            cands.append(c)
    for c in (slugify(name), slugify(name, drop_stopwords=True),
              slugify(name).replace("", "")):
        if c and c not in cands:
            cands.append(c)
    hyph = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    if hyph not in cands:
        cands.append(hyph)
    return [c for c in cands if len(c) >= 2][:6]


